                        </p>
                        <p style="color:#6c757d;line-height:1.9;font-size:1.05rem;">
                            During this era, the tournament format was further refined, with the group stage, quarter-finals, semi-finals, and finals structure becoming the standard. The introduction of knockout rounds added drama and excitement, with underdog counties occasionally upsetting the established powerhouses.
                        </p>
                        <p style="color:#6c757d;line-height:1.9;font-size:1.05rem;">
