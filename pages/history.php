                        <span class="year-badge me-3" style="font-size:0.9rem;">Origins</span>
                        <h2 class="mb-0 fw-bold">The Birth of County Sports (1950s &ndash; 1960s)</h2>
                    </div>
                    <div class="ps-4" style="border-left:3px solid #dc3545;">
                        <p style="color:#6c757d;line-height:1.9;font-size:1.05rem;">
                            The concept of inter-county sports competitions in Liberia traces its roots to the 1950s and 1960s, during a period of growing national consciousness and identity. As Liberia matured as a nation, there was an increasing desire to foster unity among its fifteen counties, each with its own distinct ethnic and cultural traditions.
                        </p>
                        <p style="color:#6c757d;line-height:1.9;font-size:1.05rem;">
                            Informal county-based football matches were organized by local communities, churches, and schools. These matches served as more than just sporting events &mdash; they were cultural gatherings that brought together people from different ethnic backgrounds, including the Kru, Grebo, Bassa, Vai, Mandingo, Gio (Dan), Mano, Kpelle, Lorma, and other groups. Through sports, these diverse communities found common ground and a shared sense of Liberian identity.
                        </p>
                        <p style="color:#6c757d;line-height:1.9;font-size:1.05rem;">
                            Football was the primary sport, with counties assembling their best players to represent their communities. These matches were cultural events that brought entire counties together, with fans traveling long distances to support their teams. The spirit of county pride was born during this era, laying the foundation for what would become Liberia's most beloved sporting tradition.
                        </p>
                        <p style="color:#6c757d;line-height:1.9;font-size:1.05rem;">
                            The informal nature of these early competitions meant there was no standardized format, no official governing body, and no consistent schedule. However, the passion and enthusiasm of the participants and fans demonstrated the unifying power of sports in a nation of diverse backgrounds and cultures.
                        </p>
