                    </div>
                    <div class="ps-4" style="border-left:3px solid #0d6efd;">
                        <p style="color:#6c757d;line-height:1.9;font-size:1.05rem;">
                            Before the Liberian civil wars, county sports competitions grew significantly in popularity and organization. The government, under the Americo-Liberian leadership, and later under indigenous leadership, began to recognize the potential of sports as a tool for national cohesion. Matches were played at the Antoinette Tubman Stadium in Monrovia and at various county grounds across the country.
                        </p>
                        <p style="color:#6c757d;line-height:1.9;font-size:1.05rem;">
                            The pre-war era saw the emergence of legendary county rivalries that would define Liberian sports culture for decades. Counties like <strong>Montserrado</strong>, <strong>Nimba</strong>, <strong>Grand Bassa</strong>, <strong>Lofa</strong>, and <strong>Grand Gedeh</strong> became powerhouses in football, drawing massive crowds and creating an atmosphere of intense but friendly competition.
                        </p>
                        <p style="color:#6c757d;line-height:1.9;font-size:1.05rem;">
                            During this period, the seeds of what would become the modern County Sports Meet were planted. The structure of county-based teams, the passion of the fans, and the importance of the competition to regional identity all took root during this formative era. The tournament also served as a talent pipeline, with standout players from county competitions being selected to represent Liberia in international matches.
                        </p>
                        <p style="color:#6c757d;line-height:1.9;font-size:1.05rem;">
                            The pre-war period also saw the beginning of kickball as a popular sport among women, though it would not be formally included in the County Sports Meet until later. Basketball also gained traction in urban areas, particularly in Montserrado and other major county capitals.
                        </p>
