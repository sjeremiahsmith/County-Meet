                        </p>
                        <p style="color:#6c757d;line-height:1.9;font-size:1.05rem;">
                            The wars claimed over 250,000 lives and displaced more than half of Liberia's population. The Samuel Kanyon Doe Sports Complex, which would later become the main venue for the revived tournament, was damaged during the conflict. County grounds across the country were similarly affected, with many being used as military bases or IDP camps.
                        </p>
                        <p style="color:#6c757d;line-height:1.9;font-size:1.05rem;">
                            However, even during the darkest periods of the conflict, the spirit of county sports survived in the hearts of displaced Liberians. In refugee camps and internally displaced persons (IDP) camps in Ghana, Guinea, C&ocirc;te d'Ivoire, and within Liberia itself, informal football matches brought moments of normalcy and hope to communities torn apart by war.
                        </p>
                        <p style="color:#6c757d;line-height:1.9;font-size:1.05rem;">
                            These informal matches served as a powerful reminder of the unity and pride that the County Sports Meet represented. They demonstrated the resilience of the Liberian people and the enduring power of sports to heal and unite, even in the most challenging circumstances.
